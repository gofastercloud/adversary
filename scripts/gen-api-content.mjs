#!/usr/bin/env node
// Generates api/lib/bundled.mjs: static JSON imports so esbuild inlines all game content into the Lambda bundle.
import { readdirSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { adversaryIdsFor } from '../engine/content.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packs = readdirSync(path.join(root, 'content/packs')).filter(f => f.endsWith('.json')).map(f => f.replace('.json', ''));
const needed = new Set();
for (const id of packs) for (const a of adversaryIdsFor(JSON.parse(readFileSync(path.join(root, 'content/packs', id + '.json'), 'utf8')))) needed.add(a);
const advs = [...needed].sort();
const core = ['taxonomy', 'cards', 'doctrines', 'relics', 'events', 'tuning', 'adversary-meta', 'achievements'];
let o = '// GENERATED by scripts/gen-api-content.mjs — do not edit.\n';
for (const c of core) o += `import core_${c.replace(/-/g, '_')} from '../../content/core/${c}.json' with { type: 'json' };\n`;
for (const p of packs) o += `import pack_${p} from '../../content/packs/${p}.json' with { type: 'json' };\n`;
for (const a of advs) o += `import adv_${a} from '../../data/adversaries/${a}.json' with { type: 'json' };\n`;
o += `import attack_techniques from '../../data/attack/techniques.json' with { type: 'json' };\nimport attack_mitigations from '../../data/attack/mitigations.json' with { type: 'json' };\nimport attack_tactics from '../../data/attack/tactics.json' with { type: 'json' };\n`;
o += `\nexport const core = { ${core.map(c => `${c.includes('-') ? `adversaryMeta` : c}: core_${c.replace(/-/g, '_')}`).join(', ')} };\n`;
o += `export const packs = { ${packs.map(p => `${JSON.stringify(p)}: pack_${p}`).join(', ')} };\n`;
o += `export const adversaries = { ${advs.map(a => `${a}: adv_${a}`).join(', ')} };\n`;
o += `export const attack = { techniques: attack_techniques, mitigations: attack_mitigations, tactics: attack_tactics };\n`;
writeFileSync(path.join(root, 'api/lib/bundled.mjs'), o);
console.log('api/lib/bundled.mjs:', packs.length, 'packs,', advs.length, 'adversaries');
